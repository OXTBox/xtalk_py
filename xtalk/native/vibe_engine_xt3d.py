_sin, _cos, _sqrt = math.sin, math.cos, math.sqrt


def _n(v):
    """a value as a number the way arithmetic reads it (empty = 0); anything else: the xTalk handler"""
    if type(v) is NumStr:
        return v.raw
    try:
        return to_num(v)
    except (XtError, TypeError):
        raise Fallback() from None


# ---------------------------------------------------------------- Mat3.Mul
_MUL = {}                                  # (pA, pB) -> answer: the same matrices are multiplied again and again


def _items9(m):
    p = m.split(',')                       # item n of m (itemDel comma); an item past the end is empty
    if len(p) < 9:
        p += [''] * (9 - len(p))
    return [_n(x) for x in p[:9]]


def mat3_mul(rt, fr):
    """function Mat3.Mul pA,pB: 3x3 row-major comma lists; answers the nine items, numberFormat'd"""
    va, vb = fr.vars.get('pa', ''), fr.vars.get('pb', '')
    if isinstance(va, dict) or isinstance(vb, dict):
        raise Fallback()
    return _mul(str.__str__(va), str.__str__(vb))   # the text: a NumStr's own text is what item n of it reads


def _mul(ta, tb):
    key = (ta, tb)
    r = _MUL.get(key)
    if r is not None:
        return r
    a, b = _items9(key[0]), _items9(key[1])
    out = []
    for r0 in (0, 3, 6):
        a0, a1, a2 = a[r0], a[r0 + 1], a[r0 + 2]
        for c in (0, 1, 2):
            out.append(fmt_num(a0 * b[c] + a1 * b[3 + c] + a2 * b[6 + c]))
    r = ','.join(out)
    if len(_MUL) > 50000:
        _MUL.clear()
    _MUL[key] = r
    return r


# ---------------------------------------------------------------- Xform.Object
_ROT = {}                                  # the three angles' text -> Mat3.RotZYX's answer


def _rot_zyx(a, b, c):
    """Mat3.RotZYX(a, b, c) of three numbers' texts"""
    key = (a, b, c)
    r = _ROT.get(key)
    if r is not None:
        return r
    rx, ry, rz = _n(a), _n(b), _n(c)
    cx, sx, cy, sy, cz, sz = _cos(rx), _sin(rx), _cos(ry), _sin(ry), _cos(rz), _sin(rz)
    f = fmt_num
    t_rz = '%s,%s,0,%s,%s,0,0,0,1' % (f(cz), f(-sz), f(sz), f(cz))
    t_ry = '%s,0,%s,0,1,0,%s,0,%s' % (f(cy), f(sy), f(-sy), f(cy))
    t_rx = '1,0,0,0,%s,%s,0,%s,%s' % (f(cx), f(-sx), f(sx), f(cx))
    r = _mul(t_rx, _mul(t_ry, t_rz))
    if len(_ROT) > 50000:
        _ROT.clear()
    _ROT[key] = r
    return r


def _angle(o, k):
    """GetObjectRotation's rule: empty or not a number = 0; the value's text"""
    v = o.get(k, '') if isinstance(o, dict) else ''
    if isinstance(v, dict):
        return '0'
    t = str.__str__(to_text(v))            # the text only (item n of the answer reads text, not a full value)
    return t if is_numeric_text(t) else '0'


def _pos(o, k):
    """GetObjectPosition(pObj, k) as Mat3.Apply's arithmetic reads it"""
    v = o.get(k, '') if isinstance(o, dict) else ''
    if isinstance(v, dict):
        raise Fallback()
    return _n(v)


def _words3(t):
    w = t.split()
    w += [''] * (3 - len(w))
    return _n(w[0]), _n(w[1]), _n(w[2])


def xform_object(rt, fr):
    """function Xform.Object pObj: the object's rotation (scene and camera folded in) and its camera-space
    position, as 12 comma items. GetObjectRotation, Mat3.RotZYX, Mat3.Mul, Mat3.Apply and GetObjectPosition
    are done here in one go (no handler calls)."""
    key = fr.vars.get('pobj', '')
    if isinstance(key, dict):
        raise Fallback()
    S = rt.S
    allo = rt.G.get('gobjecttransforms', '')
    o = allo.get(to_text(key), '') if isinstance(allo, dict) else ''
    rot = _rot_zyx(_angle(o, 'rotX'), _angle(o, 'rotY'), _angle(o, 'rotZ'))
    scm, cm, ft = S.get('sscenecamm', ''), S.get('scamm', ''), S.get('sframet', '')
    if isinstance(scm, dict) or isinstance(cm, dict) or isinstance(ft, dict):
        raise Fallback()
    m = _mul(str.__str__(to_text(scm)), rot)
    px, py, pz = _pos(o, 'x'), _pos(o, 'y'), _pos(o, 'z')
    c = _items9(str.__str__(to_text(cm)))
    f = fmt_num
    tx = f(c[0] * px + c[1] * py + c[2] * pz)      # Mat3.Apply answers words of numberFormat'd text
    ty = f(c[3] * px + c[4] * py + c[5] * pz)
    tz = f(c[6] * px + c[7] * py + c[8] * pz)
    a1, a2, a3 = _words3(to_text(ft))
    return '%s,%s,%s,%s' % (m, f(a1 + float(tx)), f(a2 + float(ty)), f(a3 + float(tz)))


# ---------------------------------------------------------------- Vibe.Color
_RGB = {}                                  # Color.ToRGB's answer for a colour's text (it reads nothing else)


def _to_rgb(rt, v):
    if isinstance(v, dict):
        raise Fallback()
    t = str.__str__(to_text(v))
    r = _RGB.get(t)
    if r is None:
        r = rt.invoke('Color.ToRGB', [t])
        if isinstance(r, dict):
            raise Fallback()
        r = str.__str__(to_text(r))
        if len(_RGB) > 5000:
            _RGB.clear()
        _RGB[t] = r
    return r


def _s(rt, k):
    v = rt.S.get(k, '')
    if isinstance(v, dict):
        raise Fallback()
    return v


def vibe_color(rt, fr):
    """function Vibe.Color pGraphic, pZ: "r,g,b,a" for a graphic's colour, faded by the view's depth bands.
    Reads only (nothing changes), so any value it was not written for goes to the xTalk."""
    g, z = fr.vars.get('pgraphic', ''), fr.vars.get('pz', '')
    if isinstance(g, dict) or isinstance(z, dict):
        raise Fallback()
    view = rt.S.get('sview', '')
    mono = view.get('mono', '') if isinstance(view, dict) else ''
    if isinstance(mono, dict):
        raise Fallback()
    if to_text(mono) != '':
        rgb = _to_rgb(rt, mono)
    else:
        orig = rt.S.get('sorigcolor', '')
        rgb = _to_rgb(rt, orig.get(to_text(g), '') if isinstance(orig, dict) else '')
    alpha = 255.0
    zt = to_text(z)
    if is_numeric_text(zt):
        bands = _s(rt, 'sviewbands')
        if not is_numeric_text(to_text(bands)):
            raise Fallback()
        nb = _n(bands)
        if num_cmp(nb, 1.0) > 0:
            near, far = _n(_s(rt, 'sviewnear')), _n(_s(rt, 'sviewfar'))
            fade = view.get('fade', '') if isinstance(view, dict) else ''
            if isinstance(fade, dict):
                raise Fallback()
            if far - near == 0:
                raise Fallback()
            band = 1.0 + float(math.trunc((_n(z) - near) * nb / (far - near)))
            band = max(1.0, min(nb, band))
            alpha = float(rnd_half_away(255.0 * (1.0 - (_n(fade) + 0.0) * (band - 1.0) / (nb - 1.0) / 100.0)))
            alpha = max(40.0, min(255.0, alpha))
    return rgb + ',' + fmt_num(alpha)


# ---------------------------------------------------------------- RotateLocalVector
def _rotate(dx, dy, dz, rx, ry, rz):
    """Z, then Y, then X, exactly as the xTalk writes it"""
    x1 = dx * _cos(rz) - dy * _sin(rz)
    y1 = dx * _sin(rz) + dy * _cos(rz)
    z1 = dz
    x2 = x1 * _cos(ry) + z1 * _sin(ry)
    z2 = -x1 * _sin(ry) + z1 * _cos(ry)
    y2 = y1
    y3 = y2 * _cos(rx) - z2 * _sin(rx)
    z3 = y2 * _sin(rx) + z2 * _cos(rx)
    x3 = x2
    return x3, y3, z3


def rotate_local_vector(rt, fr):
    """function RotateLocalVector tVX,tVY,tVZ,tRotX,tRotY,tRotZ: answers "x y z" (numberFormat'd)"""
    v = fr.vars
    x, y, z = _rotate(_n(v.get('tvx', '')), _n(v.get('tvy', '')), _n(v.get('tvz', '')),
                      _n(v.get('trotx', '')), _n(v.get('troty', '')), _n(v.get('trotz', '')))
    return '%s %s %s' % (fmt_num(x), fmt_num(y), fmt_num(z))


def _rotated_words(dx, dy, dz, rx, ry, rz):
    """RotateLocalVector(...) then word 1, 2, 3 of it as numbers (the text's numbers: six decimals)"""
    if dx == 0 and dy == 0 and dz == 0:    # a still vector stays 0 0 0 (-0 shows as 0)
        return 0.0, 0.0, 0.0
    x, y, z = _rotate(dx, dy, dz, rx, ry, rz)
    return float(fmt_num(x)), float(fmt_num(y)), float(fmt_num(z))


# ---------------------------------------------------------------- UpdateObjectTransforms
def update_object_transforms(rt, fr):
    """on UpdateObjectTransforms: every object in gObjectTransforms advances one step (rotation speed,
    local thrust, braking, top speed, world and local velocity). Same keys made, in the same order."""
    G = rt.G
    src = G.get('gobjecttransforms', '')
    if not isinstance(src, dict):          # no objects: the xTalk puts the same value back
        G['gobjecttransforms'] = src
        return ''
    for o in src.values():                 # anything unusual: the xTalk handler (nothing changed yet)
        if not isinstance(o, dict):
            raise Fallback()
        for k in ('rotSpeedX', 'rotSpeedY', 'rotSpeedZ', 'rotX', 'rotY', 'rotZ', 'localAx', 'localAy', 'localAz',
                  'vx', 'vy', 'vz', 'localBrake', 'maxWorldSpeed', 'localVx', 'localVy', 'localVz', 'x', 'y', 'z'):
            v = o.get(k, '')
            if type(v) is not NumStr and (isinstance(v, dict) or not _isnum(v)):
                raise Fallback()
    objs = copy.deepcopy(src)              # put gObjectTransforms into tObjA
    for o in objs.values():
        g = o.get
        rx = _n(g('rotX', '')) + _n(g('rotSpeedX', ''))      # add rotSpeedX to rotX
        o['rotX'] = numstr(rx)
        ry = _n(g('rotY', '')) + _n(g('rotSpeedY', ''))
        o['rotY'] = numstr(ry)
        rz = _n(g('rotZ', '')) + _n(g('rotSpeedZ', ''))
        o['rotZ'] = numstr(rz)
        # the angles as the xTalk passes them: the stored values (full value kept)
        rx, ry, rz = o['rotX'].raw, o['rotY'].raw, o['rotZ'].raw
        ax, ay, az = _rotated_words(_n(g('localAx', '')), _n(g('localAy', '')), _n(g('localAz', '')), rx, ry, rz)
        vx = _n(g('vx', '')) + ax
        o['vx'] = numstr(vx)
        vy = _n(g('vy', '')) + ay
        o['vy'] = numstr(vy)
        vz = _n(g('vz', '')) + az
        o['vz'] = numstr(vz)
        vx, vy, vz = o['vx'].raw, o['vy'].raw, o['vz'].raw
        speed = _sqrt(vx * vx + vy * vy + vz * vz)
        brake = _n(g('localBrake', ''))
        if num_cmp(brake, 0) > 0 and num_cmp(speed, 0) > 0:
            if num_cmp(speed, brake) <= 0:
                o['vx'] = numstr(0.0)
                o['vy'] = numstr(0.0)
                o['vz'] = numstr(0.0)
            else:
                f = (speed - brake) / speed
                o['vx'] = numstr(vx * f)
                o['vy'] = numstr(vy * f)
                o['vz'] = numstr(vz * f)
        top = _n(g('maxWorldSpeed', ''))
        if num_cmp(top, 0) > 0:
            vx, vy, vz = o['vx'].raw, o['vy'].raw, o['vz'].raw
            speed = _sqrt(vx * vx + vy * vy + vz * vz)
            if num_cmp(speed, top) > 0:
                f = top / speed
                o['vx'] = numstr(vx * f)
                o['vy'] = numstr(vy * f)
                o['vz'] = numstr(vz * f)
        lx, ly, lz = _rotated_words(_n(g('localVx', '')), _n(g('localVy', '')), _n(g('localVz', '')), rx, ry, rz)
        dx = o['vx'].raw + lx
        dy = o['vy'].raw + ly
        dz = o['vz'].raw + lz
        o['x'] = numstr(_n(g('x', '')) + dx)
        o['y'] = numstr(_n(g('y', '')) + dy)
        o['z'] = numstr(_n(g('z', '')) + dz)
    G['gobjecttransforms'] = objs          # put tObjA into gObjectTransforms
    return ''


def _isnum(v):
    if v == '':
        return True
    try:
        to_num(v)
        return True
    except (XtError, TypeError):
        return False


