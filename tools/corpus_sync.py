#!/usr/bin/env python3
"""corpus_sync.py - keep xtalk_py/corpus up to date and describe it.

    python3 tools/corpus_sync.py            refresh copies, rebuild INDEX.md and index.json
    python3 tools/corpus_sync.py --check    only report what is new, changed or missing

corpus/sources.json is the catalogue: one entry per script with its corpus file, the
project file it is copied from ("source", relative to ~/projects; null for scripts that
live only in the corpus), and a description written for people, Claude and Spark.

For each entry with a source, the copy is replaced when the project's file differs.
Then every script is measured (lines, handlers, header comment) and two indexes are
written:
  corpus/INDEX.md     a table to read
  corpus/index.json   the same for programs and local models: per script its title,
                      description, kind, tags, origin, size and handler names
Files dropped into corpus/inbox/ are listed so they can be catalogued.
"""
import hashlib, json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORPUS = os.path.join(ROOT, 'corpus')
PROJECTS = os.path.dirname(ROOT)
HANDLER = re.compile(r'^\s*(?:private\s+)?(on|function|command|getprop|setprop)\s+([A-Za-z0-9_.]+)', re.I | re.M)


def read(path):
    with open(path, 'rb') as f:
        return f.read()


def measure(path):
    text = read(path).decode('utf-8', 'replace').replace('\r\n', '\n').replace('\r', '\n')
    lines = text.split('\n')
    seen, handlers = set(), []
    for kind, name in HANDLER.findall(text):
        if name.lower() not in seen:
            seen.add(name.lower())
            handlers.append(name)
    header = []
    for line in lines[:40]:
        s = line.strip()
        if s.lower().startswith('script "'):
            continue
        if s.startswith(('--', '#', '//')):
            s = s.lstrip('-#/ ').rstrip('=-# ')
            if s:
                header.append(s)
            if len(header) >= 6:
                break
        elif s:
            break
    return {'lines': len(lines), 'bytes': len(text.encode('utf-8')), 'handlers': handlers,
            'header': header, 'script_only_stack': text.lstrip('﻿').lower().startswith('script "')}


def main():
    check = '--check' in sys.argv
    with open(os.path.join(CORPUS, 'sources.json'), encoding='utf-8') as f:
        cat = json.load(f)
    changed, missing, index = [], [], []
    for e in cat['entries']:
        dest = os.path.join(CORPUS, e['file'])
        if e.get('source'):
            src = os.path.join(PROJECTS, e['source'])
            if not os.path.isfile(src):
                missing.append(e['source'])
            elif not os.path.isfile(dest) or read(src) != read(dest):
                changed.append(e['file'])
                if not check:
                    os.makedirs(os.path.dirname(dest), exist_ok=True)
                    shutil.copy2(src, dest)
        if not os.path.isfile(dest):
            missing.append(e['file'])
            continue
        m = measure(dest)
        item = dict(e)
        item['origin'] = ('copy of ~/projects/' + e['source']) if e.get('source') else 'lives only here'
        item.update(m)
        item['sha1'] = hashlib.sha1(read(dest)).hexdigest()[:12]
        index.append(item)
    listed = {e['file'] for e in cat['entries']}
    inbox = sorted(os.path.relpath(os.path.join(r, n), CORPUS)
                   for r, _, ns in os.walk(os.path.join(CORPUS, 'inbox')) for n in ns
                   if n != 'README.md' and 'Zone.Identifier' not in n)
    unlisted = sorted(os.path.relpath(os.path.join(r, n), CORPUS)
                      for r, _, ns in os.walk(CORPUS) for n in ns
                      if n.endswith(('.livecodescript', '.txt'))
                      and not os.path.relpath(r, CORPUS).startswith('inbox')
                      and os.path.relpath(os.path.join(r, n), CORPUS) not in listed)

    print(('would refresh' if check else 'refreshed'), len(changed), 'copies' + (':' if changed else ''))
    for c in changed:
        print('  ', c)
    for x in missing:
        print('MISSING', x)
    for x in unlisted:
        print('NOT IN sources.json', x)
    for x in inbox:
        print('INBOX (to catalogue)', x)
    if check:
        return

    with open(os.path.join(CORPUS, 'index.json'), 'w', encoding='utf-8') as f:
        json.dump({'about': 'LiveCode script corpus: owner scripts, libraries, games and tools. '
                            'Generated by xtalk_py/tools/corpus_sync.py from corpus/sources.json; '
                            'paths are relative to xtalk_py/corpus.',
                   'scripts': index}, f, indent=1)
    total = sum(i['lines'] for i in index)
    out = ['# LiveCode script corpus: index', '',
           'Generated by `tools/corpus_sync.py` from `sources.json` (edit descriptions there). '
           '%d scripts, %d lines. See `README.md` for how the corpus works.' % (len(index), total), '']
    groups = {}
    for i in index:
        groups.setdefault(i['file'].split('/')[0], []).append(i)
    for g in sorted(groups):
        out += ['## ' + g, '', '| Script | Lines | Handlers | What it is |', '|---|---|---|---|']
        for i in groups[g]:
            desc = i['description'].replace('|', '/')
            origin = '' if not i.get('source') else ' *(copy of `%s`)*' % i['source']
            out.append('| **%s**<br>`%s` | %d | %d | %s%s |' % (i['title'], i['file'], i['lines'],
                                                           len(i['handlers']), desc, origin))
        out.append('')
    with open(os.path.join(CORPUS, 'INDEX.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(out))
    print('wrote INDEX.md and index.json:', len(index), 'scripts,', total, 'lines')


if __name__ == '__main__':
    main()
